// 中文數字對照
const CN_DIGITS = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];

/**
 * 把錢數轉「X兩Y錢」中文字串
 * @param {number} qian 總錢數
 * @returns {string}
 */
function formatWeight(qian) {
  const liang = Math.floor(qian / 10);
  const q = qian % 10;

  // 兩數轉中文（支援 1–10）
  let liangText;
  if (liang <= 10) {
    liangText = CN_DIGITS[liang];
  } else {
    const tens = Math.floor(liang / 10);
    const ones = liang % 10;
    liangText = (tens > 1 ? CN_DIGITS[tens] : '') + '十' + (ones > 0 ? CN_DIGITS[ones] : '');
  }

  const qianText = q > 0 ? CN_DIGITS[q] + '錢' : '';
  return liangText + '兩' + qianText;
}

/**
 * 計算袁天罡稱骨重量
 * @param {string} yearGanZhi  年柱干支（如 '庚午'）
 * @param {number} lunarMonth  農曆月份（1–12）
 * @param {number} lunarDay    農曆日（1–30）
 * @param {string} hourZhi     時柱地支（如 '巳'）
 * @returns {{ yearQian, monthQian, dayQian, hourQian, totalQian, weightText, verse }}
 */
function getChengGu(yearGanZhi, lunarMonth, lunarDay, hourZhi) {
  // 查年柱
  if (!(yearGanZhi in YEAR_QIAN)) {
    throw new Error(`未知年柱干支：${yearGanZhi}`);
  }
  const yearQian = YEAR_QIAN[yearGanZhi];

  // 查月柱
  if (lunarMonth < 1 || lunarMonth > 12 || !Number.isInteger(lunarMonth)) {
    throw new Error(`月份超範圍：${lunarMonth}`);
  }
  const monthQian = MONTH_QIAN[lunarMonth];

  // 查日柱
  if (lunarDay < 1 || lunarDay > 30 || !Number.isInteger(lunarDay)) {
    throw new Error(`日期超範圍：${lunarDay}`);
  }
  const dayQian = DAY_QIAN[lunarDay];

  // 查時柱
  if (!(hourZhi in HOUR_QIAN)) {
    throw new Error(`未知時柱地支：${hourZhi}`);
  }
  const hourQian = HOUR_QIAN[hourZhi];

  const totalQian = yearQian + monthQian + dayQian + hourQian;
  const weightText = formatWeight(totalQian);

  // 查歌訣（限制在 21–71 範圍）
  const clampedKey = Math.max(21, Math.min(71, totalQian));
  const verse = VERSES[clampedKey] || '';

  return { yearQian, monthQian, dayQian, hourQian, totalQian, weightText, verse };
}

